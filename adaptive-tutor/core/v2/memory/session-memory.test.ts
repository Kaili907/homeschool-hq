import assert from "node:assert/strict";
import test from "node:test";
import {
  MAXIMUM_INTERVENTION_COUNT,
  MAXIMUM_STRATEGY_REFERENCES,
  MAXIMUM_TUTOR_MEMORY_ENTRIES,
  MAXIMUM_TUTOR_MEMORY_TTL_MS,
  MAXIMUM_UNDERSTOOD_STEP_REFERENCES,
  MinimizedTutorSessionEndSchema,
  TutorSessionMemoryStateSchema,
  TutorSessionMemoryStore,
} from "./index.js";
import { validateExact } from "../contracts/validation.js";

const baseScope = {
  scopeKind: "trusted-study-tutor-scope",
  householdScopeRef: "household-scope:opaque-a",
  learnerScopeRef: "learner-scope:opaque-a",
  sessionRef: "session:math-a",
  interactionRef: "interaction:tutor-a",
  lessonRef: "lesson:fraction-a",
} as const;

function openRequest(memoryRef = "memory:tutor-a") {
  return { memoryRef, scope: baseScope, ttlMs: 60_000 } as const;
}

function accessRequest(memoryRef = "memory:tutor-a") {
  return { memoryRef, scope: baseScope } as const;
}

test("accepts only bounded structured Tutor session state", () => {
  const store = new TutorSessionMemoryStore({ now: () => Date.parse("2026-08-13T20:00:00.000Z") });
  assert.equal(store.open(openRequest()).status, "accepted");
  const result = store.update({
    ...accessRequest(),
    patch: {
      strategiesTried: ["strategy:number-line", "strategy:equal-groups"],
      visualExplanationTried: true,
      hintLevelUsed: "concept-cue",
      currentConceptRef: "concept:fractions",
      currentMisconceptionHypothesisRef: "misconception:parts-not-equal",
      understoodStepRefs: ["step:identify-whole"],
      lastTutorAction: "show-example",
      interventionCount: 2,
    },
  });
  assert.equal(result.status, "accepted");
  if (result.status !== "accepted") return;
  assert.equal(validateExact(TutorSessionMemoryStateSchema, result.state).status, "accepted");
  assert.deepEqual(result.state.strategiesTried, [
    "strategy:number-line",
    "strategy:equal-groups",
  ]);
  assert.equal(result.state.persistenceAllowed, false);
  assert.equal(result.state.authoritativeStudyHistory, false);
  assert.equal(result.state.rawProseStored, false);
});

test("rejects raw transcripts and unrestricted prose fields", () => {
  const store = new TutorSessionMemoryStore();
  store.open(openRequest());
  for (const forbiddenPatch of [
    { rawTranscript: "Learner said an entire private conversation." },
    { conversation: ["raw turn one", "raw turn two"] },
    { tutorProse: "The full explanation generated by Tutor." },
    { privateNotes: "Anything unrestricted." },
  ]) {
    assert.deepEqual(store.update({ ...accessRequest(), patch: forbiddenPatch }), {
      status: "rejected",
      code: "INVALID_MEMORY_PATCH",
      tutorMayUseMemory: false,
    });
  }
});

