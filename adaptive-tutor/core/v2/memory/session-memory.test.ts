  const store = new TutorSessionMemoryStore();
  store.open(openRequest());
  assert.deepEqual(store.reset(accessRequest()), { status: "reset" });
  assert.deepEqual(store.read(accessRequest()), {
    status: "rejected",
    code: "MEMORY_NOT_FOUND",
    tutorMayUseMemory: false,
  });
