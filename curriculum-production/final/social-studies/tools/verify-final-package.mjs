#!/usr/bin/env node

import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const ROOT = resolve(import.meta.dirname, '../../../..')
const OUT = join(ROOT, 'curriculum-production/final/social-studies')
const readJson = (name) => JSON.parse(readFileSync(join(OUT, name), 'utf8'))
const fail = (message) => { throw new Error(message) }
const assert = (condition, message) => { if (!condition) fail(message) }

const manifest = readJson('production-manifest.json')
const records = readJson('lesson-records.json')
const registry = readJson('verified-static-sources.json')
const policy = readJson('runtime-source-policy.json')
const gateH3 = readJson('gate-h3-report.json')
const evidence = readJson('source-contract-evidence.json')
const dynamicSchema = readJson('dynamic-attachment-metadata.schema.json')
const hsContract = readJson('high-school-source-contract.json')
const jsonl = readFileSync(join(OUT, 'lesson-records.jsonl'), 'utf8').trim().split('\n').map(JSON.parse)

assert(manifest.classification === 'FINAL_SOCIAL_PRODUCTION_READY', 'classification')
assert(manifest.contentRepairClassification === 'SOCIAL_CONTENT_READY_FOR_CONVERGENCE', 'content repair classification')
assert(records.length === 972 && jsonl.length === 972, '972/972 lesson records')
assert(new Set(records.map((record) => record.lessonId)).size === 972, 'unique lesson IDs')
assert(records.every((record) => record.productionPackage?.admittedInPackage), 'all packages admitted')
assert(records.every((record) => record.scoringAuthority?.authorityState === 'SCORABLE_CRITERIA_PRESENT'), 'all scoring authorities present')
assert(records.every((record) => record.scoringAuthority?.tutorMayWriteGradedArgument === false), 'tutor boundary')
assert(records.every((record) => record.taskSourceBinding?.tutorMayWriteGradedArgument === false), 'task-binding tutor boundary')
assert(records.every((record) => record.sourceReadiness?.policy && record.sourceMetadataProvenance?.state), 'source policy/provenance complete')
assert(records.filter((record) => record.sourceReadiness.policy === 'STATIC_VERIFIED_SOURCE').length === 960, '960 static lessons')
const dynamic = records.filter((record) => record.sourceReadiness.policy === 'DYNAMIC_SOURCE_REQUIRED')
assert(dynamic.length === 12, '12 dynamic lessons')
assert(dynamic.every((record) => record.lessonId.startsWith('ma-g3-social-studies-u09-')), 'dynamic scope')
assert(dynamic.every((record) => record.sourceReadiness.runtimeState === 'PENDING_SOURCE_ATTACHMENT'), 'dynamic pending state')
assert(dynamic.every((record) => record.sourceReadiness.packageAdmission === 'ADMITTED'), 'dynamic package admission')
assert(dynamic.every((record) => record.sourceReadiness.lessonLaunch === 'DISABLED' && record.sourceReadiness.scoring === 'DISABLED'), 'dynamic runtime hold')
assert(records.every((record) => record.sourceReadiness.policy !== 'UNRESOLVED'), 'zero unresolved')
assert(records.filter((record) => record.lessonId.startsWith('ma-g7-social-studies-u02-')).every((record) => record.sourceReadiness.policy === 'STATIC_VERIFIED_SOURCE'), 'Grade 7 Era 1 static')
assert(Object.values(registry.sources).every((source) => source.title && (source.url || source.locator) && source.verification.status === 'VERIFIED'), 'verified registry metadata')
assert(Object.values(registry.sources).every((source) => source.rightsCategory && source.rightsAndAccess), 'rights registry metadata')
assert(Object.values(registry.sources).every((source) => source.quotationStored === false), 'no source text')
assert(Object.keys(registry.lessonCoverage).length === 960, 'static lesson registry coverage')
assert(registry.totals.registryVerifiedStaticLessons === 960, 'registry-verified coverage')
assert(registry.totals.pinnedUpstreamVerifiedAssertionLessons === 0, 'zero pinned upstream assertions')
assert(registry.totals.highSchoolAssertionsResolved === 432, '432 high-school assertions resolved')
assert(registry.totals.taskSourceBindings === 960, '960 task/source bindings')
const staticRecords = records.filter((record) => record.sourceReadiness.policy === 'STATIC_VERIFIED_SOURCE')
assert(staticRecords.every((record) => record.sourceMetadataProvenance.state === 'VERIFIED_STATIC_METADATA'), 'all static records have verified metadata')
assert(staticRecords.every((record) => record.sourceReadiness.anchorSourceKeys.length >= record.taskSourceBinding.minimumSourceRecords), 'static source set sufficient for task')
assert(staticRecords.every((record) => record.taskSourceBinding.state === 'BOUND_TO_VERIFIED_SOURCE_SET'), 'static task/source linkage')
assert(staticRecords.every((record) => record.taskSourceBinding.bindingRationale && record.sourceReadiness.anchorSourceKeys.every((sourceKey) => registry.sources[sourceKey])), 'static semantic source linkage')
assert(staticRecords.filter((record) => /one primary source and one secondary source/i.test(`${record.taskSourceBinding.taskShape} ${record.taskSourceBinding.evidenceRequirement}`)).every((record) => record.taskSourceBinding.primarySourceAvailable && record.taskSourceBinding.secondarySourceAvailable), 'primary/secondary role coverage')
assert(staticRecords.every((record) => record.taskSourceBinding.learnerCitationRequired), 'learner citation authority')
const hsRecords = staticRecords.filter((record) => /^ma-g(?:9|10|11|12)-/.test(record.lessonId))
assert(hsRecords.length === 432, '432 high-school static lessons')
assert(hsRecords.every((record) => record.sourceReadiness.anchorSourceKeys.length >= 3), 'high-school source set completeness')
assert(hsRecords.every((record) => record.sourceReadiness.anchorSourceKeys.some((sourceKey) => sourceKey.startsWith('academy-'))), 'high-school Academy-original secondary guide')
assert(policy.dynamicContract.noInvention && policy.emptyAttachmentTemplate, 'dynamic metadata contract')
assert(policy.attachmentMetadataContract.schemaSha256 && policy.attachmentMetadataContract.sourceBodyStored === false, 'dynamic attachment schema contract')
assert(dynamicSchema.required.length >= 30, 'complete dynamic required metadata')
assert(dynamicSchema.properties.quotedTextStored.const === false, 'dynamic source text excluded')
assert(dynamicSchema['x-readiness'].schemaValidationAloneDoesNotMakeReady === true, 'dynamic schema does not imply readiness')
assert(dynamic.every((record) => record.sourceReadiness.requiredAttachmentFields.length === dynamicSchema.required.length), 'dynamic required fields projected')
assert(hsContract.policy.quotationStored === false && Object.keys(hsContract.unitSets).length === 36, 'high-school source contract')
assert(policy.packageAdmission.dynamicLessonsGloballyProductionUnready === false, 'dynamic global readiness policy')
const g7 = staticRecords.filter((record) => record.lessonId.startsWith('ma-g7-social-studies-u02-'))
assert(g7.length === 12, 'Grade 7 Smithsonian lesson count')
assert(g7.every((record) => record.sourceReadiness.anchorSourceKeys.every((sourceKey) => sourceKey.startsWith('si-nmnhanthro-'))), 'Grade 7 Smithsonian keys preserved')
assert(new Set(g7.flatMap((record) => record.sourceReadiness.anchorSourceKeys)).size === 4, 'Grade 7 four approved anchors')
assert([...new Set(g7.flatMap((record) => record.sourceReadiness.anchorSourceKeys))].every((sourceKey) => registry.sources[sourceKey].rightsCategory === 'CC0'), 'Grade 7 Smithsonian CC0')
assert(evidence.totals.unresolvedStaticAssertions === 0, 'evidence: zero unresolved static assertions')
assert(evidence.totals.highSchoolSourceAssertionsResolved === 432, 'evidence: high-school assertions')
assert(evidence.totals.rightsFailures === 0 && evidence.totals.verificationFailures === 0, 'evidence: rights and verification')
assert(evidence.totals.adultScoringLeaks === 0, 'evidence: adult scoring leaks')
assert(evidence.taskSourceBinding.insufficientBindings === 0, 'evidence: source/task sufficiency')
assert(evidence.taskSourceBinding.primarySecondaryRoleGaps === 0, 'evidence: primary/secondary source roles')
assert(gateH3.totals.ready === 960 && gateH3.totals.needsHumanReview === 12 && gateH3.totals.notReady === 0, 'H3 standard result')
assert(gateH3.admissionOverlay.productionPackagesAdmitted === 972 && gateH3.admissionOverlay.unresolvedWithoutPolicy === 0, 'H3 admission overlay')

for (const record of records) {
  const blob = execFileSync('git', ['rev-parse', `${record.productionPackage.inputSha}:${record.productionPackage.path}`], { cwd: ROOT, encoding: 'utf8' }).trim()
  assert(blob === record.productionPackage.gitBlobSha1, `package checksum ${record.lessonId}`)
}

for (const line of readFileSync(join(OUT, 'checksums.sha256'), 'utf8').trim().split('\n')) {
  const [expected, name] = line.split(/\s{2}/)
  const actual = createHash('sha256').update(readFileSync(join(OUT, name))).digest('hex')
  assert(actual === expected, `checksum ${name}`)
}

console.log('PASS: FINAL_SOCIAL_PRODUCTION_READY')
console.log('PASS: 972/972 packages, scoring authorities, source policies, and provenance states')
console.log('PASS: 960 STATIC_VERIFIED_SOURCE; 12 DYNAMIC_SOURCE_REQUIRED/PENDING_SOURCE_ATTACHMENT')
console.log('PASS: 432/432 high-school assertions resolved to verified source records; 0 pinned assertions')
console.log('PASS: 960/960 static lesson tasks bound to sufficient source sets with valid rights metadata')
console.log(`PASS: dynamic attachment metadata schema (${dynamicSchema.required.length} required fields); no source body stored`)
console.log('PASS: Grade 7 Smithsonian source keys preserved and CC0')
console.log('PASS: 0 tutor/adult graded-argument authorship leaks')
console.log('PASS: Production Gate H3 admission overlay; 0 unresolved-without-policy')
console.log('PASS: package blobs and artifact SHA-256 checksums')
