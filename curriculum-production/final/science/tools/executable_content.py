def build_executable_content(
    lesson: dict,
    course: dict,
    authority: dict,
    data_bearing: bool,
) -> dict:
    evidence_rows = _reference_rows(authority)
    phase_task = PHASE_TASKS.get(
        lesson["phase"],
        "Use the supplied evidence record to complete the stated learning objectives and cite evidence IDs.",
    )
    content = {
        "version": CONTENT_VERSION,
        "completion_mode": "PACKAGE_ALONE",
        "science_brief": [
            row["information"] for row in evidence_rows
        ],
        "case": {
            "title": f"Evidence check: {lesson['focus']}",
            "claim_to_test": _candidate_claim(authority, lesson["focus"]),
            "claim_status": "candidate claim; the learner decides from the supplied record",
        },
        "supplied_evidence": {
            "title": "Complete reference-evidence record for this lesson",
            "columns": ["Evidence ID", "Type", "Information"],
            "rows": evidence_rows,
            "provenance": (
                f"Manuel Academy Science learner brief for topic {authority['topic_key']}, "
                f"derived from the reviewed correctness source {authority['authored']['file']}."
            ),
        },
        "unit_connections": list(lesson["unit"].get("topics", [])),
        "unit_performance_task": lesson["unit"].get("performance_task", ""),
        "bound_task": {
            "question": (
                f"What does evidence E1 through E{len(evidence_rows)} justify about "
                f"{lesson['focus']}, and does it support the candidate claim?"
            ),
            "phase_directions": phase_task,
            "steps": [
                "Read the science brief and the candidate claim.",
                "Use the supplied evidence IDs; do not refer to an unseen source or an activity from another lesson.",
                phase_task,
                "Cite evidence IDs beside each conclusion and state one limit of the supplied record.",
                "Check the response against today's success criteria and revise one part.",
            ],
        },
        "materials_complete": True,
        "inputs_complete": True,
        "placeholder_free": True,
        "physical_result_disclosed_before_collection": False,
    }

    if data_bearing and course["family"] == "k8":
        investigation = _document_investigation(lesson, evidence_rows)
        content["investigation"] = investigation
        content["primary_route"] = {
            "kind": "DOCUMENT_INVESTIGATION",
            "materials": investigation["materials"],
            "procedure": investigation["procedure"],
            "safety": investigation["safety"],
            "recording_columns": investigation["recording_columns"],
            "cleanup": investigation["cleanup"],
        }
        content["equal_credit_route"] = {
            "kind": "ACCESSIBLE_EVIDENCE_SIMULATION",
            "complete": True,
            "materials": ["the evidence record on this sheet", "an accessible response tool"],
            "input": content["supplied_evidence"],
            "procedure": [
                "Have the evidence rows read aloud, enlarged, or converted to tactile/one-row-at-a-time cards.",
                "For each row, state supports, challenges, or does not decide and give the reason.",
                "Produce the same conclusion, limitation, and revision required by the primary route.",
            ],
            "same_scoring_ceiling": True,
        }
    elif data_bearing:
        alternative = HS_ALTERNATIVE_DATA[(course["course_id"], lesson["unit_number"])]
        content["primary_route"] = {
            "kind": "H4_PHYSICAL_INVESTIGATION",
            "authority": "The pinned H4 materials, safe order, stop conditions, and disposal rendered elsewhere on this sheet.",
            "source_task": lesson["student_activity"],
            "complete": bool(lesson["materials"]),
        }
        content["equal_credit_route"] = {
            "kind": "DELIVERED_MODEL_DATA_ALTERNATIVE",
            "complete": True,
            "materials": ["this supplied model-data table", "paper", "pencil", "calculator if desired"],
            "input": alternative,
            "procedure": [
                "Choose this route instead of the physical route; it earns the same maximum score.",
                "Read the model rule and label every supplied quantity as MODEL OUTPUT.",
                alternative["task"],
                "Show calculations, cite row labels, state a limitation of the model, and answer the lesson analysis questions.",
                "Do not combine these model outputs with measurements from the physical route or call them observations.",
            ],
            "same_scoring_ceiling": True,
            "does_not_predict_physical_route": True,
        }
    else:
        content["primary_route"] = {
            "kind": "BOUND_REFERENCE_EVIDENCE_TASK",
            "complete": True,
            "materials": ["this complete learner sheet", "course notebook or response space", "accessible response tool"],
        }
        content["equal_credit_route"] = {
            "kind": "ACCESSIBLE_RESPONSE_ROUTE",
            "complete": True,
            "materials": ["the supplied evidence record", "a spoken, typed, drawn, or tactile response mode"],
            "procedure": [
                f"Use the same E1-E{len(evidence_rows)} record and answer the same bound question.",
                "Respond in an accessible mode without changing the evidence or success criteria.",
            ],
            "same_scoring_ceiling": True,
        }

    return content


def production_materials(lesson: dict, course: dict, content: dict, data_bearing: bool) -> list[str]:
    """Return materials the rendered package actually supplies or names."""
    if data_bearing and course["family"] == "hs":
        source = [
            item
            for item in lesson["materials"]
            if not item.lower().startswith("no ")
            and "printed or on-screen text, data table, or model for this lesson"
            not in item.lower()
            and "unit-specific source, model, manipulatives, safe materials" not in item.lower()
        ]
        alternative = content["equal_credit_route"]["materials"]
        return list(dict.fromkeys([*source, *alternative]))
    if data_bearing:
        return list(content["primary_route"]["materials"])
    return list(content["primary_route"]["materials"])
