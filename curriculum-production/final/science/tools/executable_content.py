"""Build package-alone learner inputs for every Science lesson.

The pinned curriculum sources establish sequence, objectives, safety, and H4
authority.  They do not, however, always ship the case, evidence, model, or
dataset a learner needs to do the stated work.  This module adds that production
layer without changing any source record or source lineage.

Reference-evidence lessons use the accepted topic relationships as readable
instructional information, then give the learner a specific claim and a closed
set of evidence to evaluate.  Investigation lessons additionally provide an
executable document investigation (K-8) or retain the H4 physical procedure and
ship a deterministic, equal-credit model dataset (High School).

Model datasets are labelled as model output, state their rule or equation, and
never pretend to be observed or published measurements.  They use systems and
conditions different from the physical route, so they do not disclose the
physical investigation's result before evidence collection.
"""

