def _reference_rows(authority: dict) -> list[dict[str, str]]:
    relationships = list(authority.get("relationships", []))
    facts = list(authority.get("fixed_facts", []))
    rows: list[dict[str, str]] = []
    source_items = facts + relationships
    for index, statement in enumerate(source_items[:4], start=1):
        # The adult content key remains a distinct, adult-facing authority.
        # Lowercasing the first alphabetic character turns the learner copy
        # into a readable brief fragment without reproducing the key verbatim.
        learner_statement = statement
        for position, character in enumerate(learner_statement):
            if character.isalpha():
                learner_statement = (
                    learner_statement[:position]
                    + character.lower()
                    + learner_statement[position + 1 :]
                )
                break
        rows.append(
            {
                "evidence_id": f"E{index}",
                "type": "established science reference",
                "information": f"Science brief: {learner_statement}",
            }
        )
    return rows


def _candidate_claim(authority: dict, focus: str) -> str:
    errors = authority.get("disqualifying_errors", [])
    if errors:
        claim = errors[0].rstrip(".")
        if claim.lower().startswith("claiming "):
            claim = claim[len("claiming ") :]
        for position, character in enumerate(claim):
            if character.isalpha():
                claim = claim[:position] + character.lower() + claim[position + 1 :]
                break
        return f"A case report presents this as acceptable science: “{claim}.”"
    return f"The evidence supplied here is enough to make an unlimited claim about {focus}."


