-- This function is the database-owned role-to-capability mapping for this
-- boundary. Callers must name the exact frozen capability; broad role markers
-- and client-supplied capability arrays are never accepted as authority.
create function academy_private.curriculum_approval_require_actor(
  p_actor_user_ref uuid,
  p_required_capability text
)
returns text
language plpgsql
stable
security definer
set search_path = pg_catalog
as $$
declare
  actor_role text;
begin
  if auth.uid() is not null
     or not academy_private.operational_is_trusted_server()
     or p_actor_user_ref is null
     or p_required_capability not in ('curriculum:read', 'curriculum:approve') then
    raise exception 'CURRICULUM_APPROVAL_REQUIRED' using errcode = '42501';
  end if;
  select assignment.role into actor_role
  from public.academy_admin_role_assignments as assignment
  where assignment.user_id = p_actor_user_ref
    and assignment.status = 'active'
    and assignment.revoked_at is null
    and (assignment.expires_at is null or assignment.expires_at > statement_timestamp())
  order by assignment.assigned_at desc, assignment.id desc
  limit 1;
  if actor_role is null
     or (p_required_capability = 'curriculum:approve' and actor_role <> 'owner') then
    raise exception 'CURRICULUM_APPROVAL_REQUIRED' using errcode = '42501';
  end if;
  return actor_role;
end;
$$;

