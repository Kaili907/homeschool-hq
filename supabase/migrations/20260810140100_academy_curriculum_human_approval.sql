create table public.academy_curriculum_draft_validation_snapshots (
  validation_snapshot_id uuid primary key default gen_random_uuid(),
  validation_sequence bigint generated by default as identity unique,
  draft_id uuid not null
    references public.academy_curriculum_drafts (draft_id) on delete restrict,
  draft_revision bigint not null check (draft_revision >= 1),
  base_release_id uuid not null
    references public.academy_curriculum_releases (release_id) on delete restrict,
  target_version text not null check (
    target_version ~ '^[0-9]+\.[0-9]+\.[0-9]+(-[a-z0-9.-]+)?$'
  ),
  schema_set_version text not null check (schema_set_version = '2.0.0'),
  engine_version text not null check (
    length(engine_version) between 1 and 80
    and engine_version ~ '^[A-Za-z0-9][A-Za-z0-9._:-]{0,79}$'
  ),
  result_sha256 text not null check (result_sha256 ~ '^[0-9a-f]{64}$'),
  validation_status text not null check (validation_status in (
    'valid', 'invalid', 'incomplete', 'unavailable', 'error'
  )),
  publication_ready boolean not null,
  blocking_count integer not null check (blocking_count between 0 and 1000000),
  blocking_error_count integer not null check (
    blocking_error_count between 0 and blocking_count
  ),
  human_review_blocker_count integer not null check (
    human_review_blocker_count between 0 and blocking_count
  ),
  validated_at timestamptz not null default statement_timestamp(),
  validated_by uuid not null references auth.users (id) on delete restrict,
  constraint academy_curriculum_validation_gate_coherence check (
    publication_ready = (
      validation_status = 'valid'
      and blocking_count = 0
      and blocking_error_count = 0
      and human_review_blocker_count = 0
    )
  ),
  constraint academy_curriculum_validation_result_unique
    unique (draft_id, draft_revision, result_sha256)
);

