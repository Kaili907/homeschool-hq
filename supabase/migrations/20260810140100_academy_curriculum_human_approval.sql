create function public.academy_admin_decide_curriculum_approval_v1(
  p_actor_user_ref uuid,
  p_draft_id uuid,
  p_draft_revision bigint,
  p_decision text,
  p_reason_code text,
  p_validation_snapshot_id uuid,
  p_request_id uuid,
  p_request_digest text,
  p_required_capability text default null
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = pg_catalog
as $$
declare
  actor_role text;
  draft_row public.academy_curriculum_drafts%rowtype;
  validation_row public.academy_curriculum_draft_validation_snapshots%rowtype;
  current_decision public.academy_curriculum_draft_approval_decisions%rowtype;
  created_approval uuid;
  replay jsonb;
  response jsonb;
begin
  actor_role := academy_private.curriculum_approval_require_actor(
    p_actor_user_ref, p_required_capability
  );
  if p_required_capability <> 'curriculum:approve'
     or p_draft_revision < 1
     or p_decision not in ('approved', 'changes_requested')
     or p_reason_code not in (
       'approval.ready',
       'changes.validation', 'changes.standards', 'changes.content_quality',
       'changes.references', 'changes.accessibility',
       'changes.safety_privacy', 'changes.other'
     )
     or (p_decision = 'approved' and p_reason_code <> 'approval.ready')
     or (p_decision = 'changes_requested' and p_reason_code not like 'changes.%')
     or (p_decision = 'approved' and p_validation_snapshot_id is null) then
    raise exception 'CURRICULUM_APPROVAL_INPUT_INVALID' using errcode = '22023';
  end if;
  replay := academy_private.curriculum_approval_replay(
    p_actor_user_ref, p_request_id, p_request_digest
  );
  if replay is not null then
    return academy_private.curriculum_approval_status_projection(p_draft_id)
      || jsonb_build_object('replayed', true);
  end if;

  select * into draft_row
  from public.academy_curriculum_drafts
  where draft_id = p_draft_id
  for update;
  if draft_row.draft_id is null then
    raise exception 'CURRICULUM_APPROVAL_DRAFT_NOT_FOUND' using errcode = 'P0002';
  end if;
  if draft_row.revision <> p_draft_revision then
    raise exception 'CURRICULUM_APPROVAL_CAS_CONFLICT' using errcode = '40001';
  end if;

  select * into current_decision
  from public.academy_curriculum_draft_approval_decisions
  where draft_id = p_draft_id and draft_revision = p_draft_revision
  order by decision_sequence desc
  limit 1;
  if current_decision.decision = 'changes_requested'
     or (current_decision.decision = 'approved' and p_decision = 'approved'
       and current_decision.validation_snapshot_id = p_validation_snapshot_id) then
    raise exception 'CURRICULUM_APPROVAL_TRANSITION_CONFLICT' using errcode = '40001';
  end if;

  if p_validation_snapshot_id is not null then
    select * into validation_row
    from public.academy_curriculum_draft_validation_snapshots
    where validation_snapshot_id = p_validation_snapshot_id;
    if validation_row.validation_snapshot_id is null
       or validation_row.draft_id <> p_draft_id
       or validation_row.draft_revision <> p_draft_revision
       or validation_row.base_release_id <> draft_row.base_release_id
       or validation_row.target_version <> draft_row.target_version
       or validation_row.schema_set_version <> draft_row.authoring_schema_version then
      raise exception 'CURRICULUM_APPROVAL_VALIDATION_BLOCKED' using errcode = '23514';
    end if;
  end if;
  if p_decision = 'approved' and (
    (select snapshot.validation_snapshot_id
     from public.academy_curriculum_draft_validation_snapshots as snapshot
     where snapshot.draft_id = p_draft_id
       and snapshot.draft_revision = p_draft_revision
     order by snapshot.validation_sequence desc
     limit 1) is distinct from p_validation_snapshot_id
    or validation_row.validation_status <> 'valid'
    or not validation_row.publication_ready
    or validation_row.blocking_count <> 0
    or validation_row.blocking_error_count <> 0
    or validation_row.human_review_blocker_count <> 0
  ) then
    raise exception 'CURRICULUM_APPROVAL_VALIDATION_BLOCKED' using errcode = '23514';
  end if;

  insert into public.academy_curriculum_draft_approval_decisions (
    draft_id, draft_revision, base_release_id, target_version,
    schema_set_version, validation_snapshot_id, validation_result_sha256,
    decision, reason_code, decided_by, reviewer_role, request_id
  ) values (
    p_draft_id, p_draft_revision, draft_row.base_release_id,
    draft_row.target_version, draft_row.authoring_schema_version,
    validation_row.validation_snapshot_id, validation_row.result_sha256,
    p_decision, p_reason_code, p_actor_user_ref, actor_role, p_request_id
  ) returning approval_id into created_approval;

  perform academy_private.curriculum_approval_append_audit(
    p_actor_user_ref, p_draft_id, draft_row.target_version, p_draft_revision,
    current_decision.decision, current_decision.reason_code,
    p_decision, p_reason_code, p_request_id
  );
  insert into academy_private.curriculum_approval_request_receipts (
    actor_user_ref, request_id, request_sha256, response
  ) values (
    p_actor_user_ref, p_request_id, p_request_digest,
    jsonb_build_object('approvalId', created_approval)
  );
  response := academy_private.curriculum_approval_status_projection(p_draft_id);
  return response || jsonb_build_object('replayed', false);
end;
$$;

