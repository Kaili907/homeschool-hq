create function academy_private.curriculum_approval_status_projection(p_draft_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog
as $$
declare
  draft_row public.academy_curriculum_drafts%rowtype;
  base_version text;
  latest_validation public.academy_curriculum_draft_validation_snapshots%rowtype;
  current_decision public.academy_curriculum_draft_approval_decisions%rowtype;
  stale_approval public.academy_curriculum_draft_approval_decisions%rowtype;
  approved_validation public.academy_curriculum_draft_validation_snapshots%rowtype;
  history jsonb;
  status_value text;
  gate_reason text;
  gate_eligible boolean := false;
  current_binding_id uuid;
  stale_binding_id uuid;
begin
  select * into draft_row
  from public.academy_curriculum_drafts
  where draft_id = p_draft_id;
  if draft_row.draft_id is null then return null; end if;
  select version into base_version
  from public.academy_curriculum_releases
  where release_id = draft_row.base_release_id;

  select * into latest_validation
  from public.academy_curriculum_draft_validation_snapshots
  where draft_id = p_draft_id and draft_revision = draft_row.revision
  order by validation_sequence desc
  limit 1;

  select * into current_decision
  from public.academy_curriculum_draft_approval_decisions
  where draft_id = p_draft_id and draft_revision = draft_row.revision
  order by decision_sequence desc
  limit 1;

  select effective.* into stale_approval
  from (
    select distinct on (decision.draft_revision) decision.*
    from public.academy_curriculum_draft_approval_decisions as decision
    where decision.draft_id = p_draft_id
      and decision.draft_revision < draft_row.revision
    order by decision.draft_revision desc, decision.decision_sequence desc
  ) as effective
  where effective.decision = 'approved'
  order by effective.draft_revision desc
  limit 1;

  if current_decision.decision = 'approved'
     and current_decision.validation_snapshot_id = latest_validation.validation_snapshot_id then
    status_value := 'approved';
    current_binding_id := current_decision.approval_id;
  elsif current_decision.decision = 'approved' then
    status_value := 'stale';
    stale_binding_id := current_decision.approval_id;
  elsif current_decision.decision = 'changes_requested' then
    status_value := 'changes_requested';
    current_binding_id := current_decision.approval_id;
  elsif stale_approval.approval_id is not null then
    status_value := 'stale';
    stale_binding_id := stale_approval.approval_id;
  else
    status_value := 'pending_review';
  end if;

  if current_decision.validation_snapshot_id is not null then
    select * into approved_validation
    from public.academy_curriculum_draft_validation_snapshots
    where validation_snapshot_id = current_decision.validation_snapshot_id;
  end if;
  if current_decision.decision = 'approved'
     and approved_validation.validation_snapshot_id is not null
     and approved_validation.draft_id = p_draft_id
     and approved_validation.draft_revision = draft_row.revision
     and approved_validation.base_release_id = draft_row.base_release_id
     and approved_validation.target_version = draft_row.target_version
     and approved_validation.schema_set_version = draft_row.authoring_schema_version
     and approved_validation.validation_snapshot_id = latest_validation.validation_snapshot_id
     and approved_validation.result_sha256 = current_decision.validation_result_sha256
     and approved_validation.validation_status = 'valid'
     and approved_validation.publication_ready
     and approved_validation.blocking_count = 0
     and approved_validation.blocking_error_count = 0
     and approved_validation.human_review_blocker_count = 0 then
    gate_eligible := true;
    gate_reason := 'approved';
  elsif current_decision.decision = 'changes_requested' then
    gate_reason := 'changes_requested';
  elsif status_value = 'stale' then
    gate_reason := 'approval_stale';
  elsif latest_validation.validation_snapshot_id is null then
    gate_reason := 'validation_missing';
  elsif not latest_validation.publication_ready then
    gate_reason := 'validation_blocked';
  else
    gate_reason := 'approval_missing';
  end if;

  select coalesce(jsonb_agg(
    academy_private.curriculum_approval_decision_projection(
      bounded.approval_id, current_binding_id
    ) order by bounded.decision_sequence desc
  ), '[]'::jsonb) into history
  from (
    select approval_id, decision_sequence
    from public.academy_curriculum_draft_approval_decisions
    where draft_id = p_draft_id
    order by decision_sequence desc
    limit 100
  ) as bounded;

  return jsonb_build_object(
    'schemaVersion', 1,
    'draftId', draft_row.draft_id,
    'draftRevision', draft_row.revision,
    'baseReleaseVersion', base_version,
    'targetVersion', draft_row.target_version,
    'schemaSetVersion', draft_row.authoring_schema_version,
    'status', status_value,
    'latestValidation', case when latest_validation.validation_snapshot_id is null
      then null else academy_private.curriculum_validation_snapshot_projection(
        latest_validation.validation_snapshot_id
      ) end,
    'currentDecision', case when current_decision.approval_id is null
      then null else academy_private.curriculum_approval_decision_projection(
        current_decision.approval_id, current_binding_id
      ) end,
    'staleApproval', case when stale_binding_id is null
      then null else academy_private.curriculum_approval_decision_projection(
        stale_binding_id, current_binding_id
      ) end,
    'history', history,
    'publishGate', jsonb_build_object(
      'eligible', gate_eligible,
      'reason', gate_reason,
      'approvalId', case when gate_eligible then current_decision.approval_id else null end,
      'draftRevision', draft_row.revision,
      'validationSnapshotId', case when gate_eligible
        then current_decision.validation_snapshot_id else null end
    )
  );
end;
$$;

create function academy_private.curriculum_approval_publish_gate_v1(
  p_draft_id uuid,
  p_draft_revision bigint
)
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog
as $$
declare
  projection jsonb;
begin
  projection := academy_private.curriculum_approval_status_projection(p_draft_id);
  if projection is null then return null; end if;
  if (projection ->> 'draftRevision')::bigint <> p_draft_revision then
    return jsonb_build_object(
      'eligible', false, 'reason', 'approval_stale', 'approvalId', null,
      'draftRevision', (projection ->> 'draftRevision')::bigint,
      'validationSnapshotId', null
    );
  end if;
  return projection -> 'publishGate';
end;
$$;

create function academy_private.curriculum_approval_replay(
  p_actor_user_ref uuid,
  p_request_id uuid,
  p_request_digest text
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = pg_catalog
as $$
declare
  receipt academy_private.curriculum_approval_request_receipts%rowtype;
begin
  if p_request_id is null or p_request_digest !~ '^[0-9a-f]{64}$' then
    raise exception 'CURRICULUM_APPROVAL_INPUT_INVALID' using errcode = '22023';
  end if;
  perform pg_advisory_xact_lock(hashtextextended(
    p_actor_user_ref::text || ':' || p_request_id::text, 0
  ));
  select * into receipt
  from academy_private.curriculum_approval_request_receipts
  where actor_user_ref = p_actor_user_ref and request_id = p_request_id
  for update;
  if receipt.request_id is null then return null; end if;
  if receipt.request_sha256 <> p_request_digest then
    raise exception 'CURRICULUM_APPROVAL_REPLAY_CONFLICT' using errcode = '40001';
  end if;
  return receipt.response;
end;
$$;

create function academy_private.curriculum_approval_append_audit(
  p_actor_user_ref uuid,
  p_draft_id uuid,
  p_target_version text,
  p_draft_revision bigint,
  p_previous_decision text,
  p_previous_reason_code text,
  p_decision text,
  p_reason_code text,
  p_correlation_id uuid
)
returns uuid
language plpgsql
volatile
security definer
set search_path = pg_catalog
as $$
declare
  old_sub text := current_setting('request.jwt.claim.sub', true);
  old_role text := current_setting('request.jwt.claim.role', true);
  old_claims text := current_setting('request.jwt.claims', true);
  event_id uuid;
begin
  perform set_config('request.jwt.claim.sub', p_actor_user_ref::text, true);
  perform set_config('request.jwt.claim.role', 'authenticated', true);
  perform set_config('request.jwt.claims', jsonb_build_object(
    'sub', p_actor_user_ref, 'role', 'authenticated',
    'academy_principal_kind', 'admin_curriculum_approval_server'
  )::text, true);
  begin
    event_id := academy_private.append_admin_audit_event_v1(
      case when p_decision = 'approved'
        then 'curriculum_approval.approve'
        else 'curriculum_approval.changes_requested' end,
      'curriculum_approval', p_draft_id::text, p_target_version,
      p_draft_revision::text,
      jsonb_build_object(
        'state', coalesce(p_previous_decision, 'pending_review'),
        'status', coalesce(p_previous_reason_code, 'review.pending'),
        'revision', p_draft_revision,
        'version', p_target_version
      ),
      jsonb_build_object(
        'state', p_decision, 'status', p_reason_code,
        'revision', p_draft_revision, 'version', p_target_version
      ),
      case when p_decision = 'approved'
        then 'curriculum.approved' else 'corrective.action' end,
      p_correlation_id
    );
  exception when others then
    perform set_config('request.jwt.claim.sub', coalesce(old_sub, ''), true);
    perform set_config('request.jwt.claim.role', coalesce(old_role, ''), true);
    perform set_config('request.jwt.claims', coalesce(old_claims, ''), true);
    raise;
  end;
  perform set_config('request.jwt.claim.sub', coalesce(old_sub, ''), true);
  perform set_config('request.jwt.claim.role', coalesce(old_role, ''), true);
  perform set_config('request.jwt.claims', coalesce(old_claims, ''), true);
  return event_id;
end;
$$;

create function public.academy_admin_record_curriculum_validation_v1(
  p_actor_user_ref uuid,
  p_draft_id uuid,
  p_draft_revision bigint,
  p_engine_version text,
  p_result_digest text,
  p_status text,
  p_publication_ready boolean,
  p_blocking_count integer,
  p_blocking_error_count integer,
  p_human_review_blocker_count integer,
  p_required_capability text default null
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = pg_catalog
as $$
declare
  draft_row public.academy_curriculum_drafts%rowtype;
  existing_snapshot public.academy_curriculum_draft_validation_snapshots%rowtype;
  resolved_snapshot uuid;
begin
  perform academy_private.curriculum_approval_require_actor(
    p_actor_user_ref, p_required_capability
  );
  if p_required_capability <> 'curriculum:read'
     or p_draft_revision < 1
     or p_engine_version is null or length(p_engine_version) not between 1 and 80
     or p_engine_version !~ '^[A-Za-z0-9][A-Za-z0-9._:-]{0,79}$'
     or p_result_digest !~ '^[0-9a-f]{64}$'
     or p_status not in ('valid', 'invalid', 'incomplete', 'unavailable', 'error')
     or p_blocking_count not between 0 and 1000000
     or p_blocking_error_count not between 0 and p_blocking_count
     or p_human_review_blocker_count not between 0 and p_blocking_count
     or p_publication_ready is distinct from (
       p_status = 'valid' and p_blocking_count = 0
       and p_blocking_error_count = 0 and p_human_review_blocker_count = 0
     ) then
    raise exception 'CURRICULUM_APPROVAL_INPUT_INVALID' using errcode = '22023';
  end if;
  select * into draft_row
  from public.academy_curriculum_drafts
  where draft_id = p_draft_id
  for key share;
  if draft_row.draft_id is null then
    raise exception 'CURRICULUM_APPROVAL_DRAFT_NOT_FOUND' using errcode = 'P0002';
  end if;
  if draft_row.revision <> p_draft_revision then
    raise exception 'CURRICULUM_APPROVAL_CAS_CONFLICT' using errcode = '40001';
  end if;
  perform pg_advisory_xact_lock(hashtextextended(
    p_draft_id::text || ':' || p_draft_revision::text || ':' || p_result_digest, 0
  ));
  select * into existing_snapshot
  from public.academy_curriculum_draft_validation_snapshots
  where draft_id = p_draft_id and draft_revision = p_draft_revision
    and result_sha256 = p_result_digest;
  resolved_snapshot := existing_snapshot.validation_snapshot_id;
  if resolved_snapshot is not null and (
    existing_snapshot.base_release_id <> draft_row.base_release_id
    or existing_snapshot.target_version <> draft_row.target_version
    or existing_snapshot.schema_set_version <> draft_row.authoring_schema_version
    or existing_snapshot.engine_version <> p_engine_version
    or existing_snapshot.validation_status <> p_status
    or existing_snapshot.publication_ready <> p_publication_ready
    or existing_snapshot.blocking_count <> p_blocking_count
    or existing_snapshot.blocking_error_count <> p_blocking_error_count
    or existing_snapshot.human_review_blocker_count <> p_human_review_blocker_count
  ) then
    raise exception 'CURRICULUM_APPROVAL_INPUT_INVALID' using errcode = '22023';
  end if;
  if resolved_snapshot is null then
    insert into public.academy_curriculum_draft_validation_snapshots (
      draft_id, draft_revision, base_release_id, target_version,
      schema_set_version, engine_version, result_sha256, validation_status,
      publication_ready, blocking_count, blocking_error_count,
      human_review_blocker_count, validated_by
    ) values (
      p_draft_id, p_draft_revision, draft_row.base_release_id,
      draft_row.target_version, draft_row.authoring_schema_version,
      p_engine_version, p_result_digest, p_status, p_publication_ready,
      p_blocking_count, p_blocking_error_count,
      p_human_review_blocker_count, p_actor_user_ref
    ) returning validation_snapshot_id into resolved_snapshot;
  end if;
  return academy_private.curriculum_validation_snapshot_projection(resolved_snapshot);
end;
$$;

